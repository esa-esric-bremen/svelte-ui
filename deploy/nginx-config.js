// Prints the nginx config template for the production image (see Dockerfile):
// serves the static UI and proxies /backend/<system_name>/... to controller-web.
//
// ${VITE_BACKEND_URI} is filled in by the nginx image at container start (envsubst),
// nginx's own $variables are left alone because no such environment variables exist.
//
// usage: node deploy/nginx-config.js > default.conf.template
import { readBackends } from './backends.js';

const locations = readBackends()
	.map(
		({ system_name, web_command_port, web_telemetry_port }) => `
    # --- ${system_name} ---
    location /backend/${system_name}/api/ {
        rewrite ^/backend/${system_name}(/api/.*)$ $1 break;
        proxy_pass http://$backend:${web_command_port};
        include /etc/nginx/conf.d/backend_command.inc;
    }
    location = /backend/${system_name}/ws {
        proxy_pass http://$backend:${web_telemetry_port}/;
        include /etc/nginx/conf.d/backend_telemetry.inc;
    }`
	)
	.join('\n');

console.log(`# generated by deploy/nginx-config.js from the robot configs, do not edit

# Docker's DNS: the backend is looked up per request (it is a variable below), so a
# restarted relay with a new address is found again. Not used for IP addresses.
resolver 127.0.0.11 valid=10s ipv6=off;

server {
    # IPv4 only
    listen 9090;
    server_name _;

    root /usr/share/nginx/html;
    set $backend \${VITE_BACKEND_URI};

    location = /healthz {
        access_log off;
        return 200 "ok\\n";
    }

    # build output with content hashes in the file names
    location /_app/immutable/ {
        expires max;
        add_header Cache-Control "public, immutable";
    }

    # single page app: every route is served by index.html, never cached so a
    # new version is picked up on reload
    location / {
        try_files $uri $uri/ /index.html;
        add_header Cache-Control "no-cache";
    }
${locations}
}`);
